/**
 * Build step for dsh-database-preview.
 *
 * The host half is plain ESM and is copied verbatim, so it stays readable in the
 * installed package. The client half must arrive as a single client-module-loader
 * factory bundle (`window.__ModuleLoader__.load({ id, factory })`), so it is
 * bundled here with React left external: the browser kernel seeds React, and a
 * second copy inside the bundle would break hooks and context.
 *
 * The banner and footer are declared to esbuild rather than prepended afterwards
 * so its source map stays accurate.
 *
 * Every artifact is produced in a staging directory and only then swapped into
 * `lib/`. `lib/` is what a running DSH loads, so a build that fails halfway — a
 * syntax error, a bad import — must leave the installed plugin untouched rather
 * than deleting the files it is serving.
 * @module dsh-database-preview/scripts/build
 */
import { build } from 'esbuild'
import { cpSync, existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const lib = join(root, 'lib')
const staging = join(root, '.lib-staging')

const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const packageName = manifest.name

const banner = [
  '// Generated by scripts/build.mjs from src/client/ — do not edit directly.',
  `window.__ModuleLoader__.load({ id: ${JSON.stringify(packageName)}, factory: (require) => {`,
  'var module = { exports: {} }; var exports = module.exports;',
].join('\n')

const footer = [
  'var __dshPlugin = module.exports;',
  'return (__dshPlugin && __dshPlugin.default && typeof __dshPlugin.default.apply === "function") ? __dshPlugin.default : __dshPlugin;',
  '} });',
].join('\n')

rmSync(staging, { recursive: true, force: true })
mkdirSync(staging, { recursive: true })

try {
  // The host half: `src/host.js` becomes the package entry, and `src/host/` its modules.
  cpSync(join(root, 'src', 'host.js'), join(staging, 'index.js'))
  if (existsSync(join(root, 'src', 'host'))) cpSync(join(root, 'src', 'host'), join(staging, 'host'), { recursive: true })

  const result = await build({
    entryPoints: [join(root, 'src', 'client', 'index.jsx')],
    outfile: join(staging, 'client.js'),
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: ['chrome120'],
    jsx: 'transform',
    // React and the shared control primitives come from the browser kernel's
    // static module table; the bundle must never carry its own copy. The
    // primitives are resolved through an indirect require in `controls.jsx`, so
    // this entry documents the intent and guards a future direct import.
    external: ['react', '@deepseek-ai/dsh-client-ui-primitives'],
    sourcemap: true,
    write: false,
    legalComments: 'none',
    logLevel: 'warning',
    banner: { js: banner },
    footer: { js: footer },
  })

  const written = []
  for (const file of result.outputFiles) {
    mkdirSync(dirname(file.path), { recursive: true })
    writeFileSync(file.path, file.contents)
    written.push(file.path)
  }

  // Only now is the installed copy replaced, and the swap is a single rename.
  rmSync(lib, { recursive: true, force: true })
  renameSync(staging, lib)
  for (const path of written) console.log(`wrote ${join(lib, path.slice(staging.length + 1))}`)
} catch (error) {
  rmSync(staging, { recursive: true, force: true })
  console.error('build failed; lib/ was left as it was')
  throw error
}
